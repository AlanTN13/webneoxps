export const COVER_OVERRIDES = Object.freeze(
  Object.fromEntries(Object.entries(COVER_EDITORIAL).map(([slug, cover]) => [slug, cover.src])),
);

export function applyCoverOverride(article) {
  if (!article || typeof article !== "object") return article;
  const coverEditorial = COVER_EDITORIAL[article.slug];
  return coverEditorial
    ? { ...article, coverImage: coverEditorial.src, coverEditorial }
    : article;
}
